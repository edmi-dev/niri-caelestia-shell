#!/usr/bin/env bash
# Fails if Hyprland-specific code remains outside the allowlist, or if NiriIpc is used
# outside the compositor boundary (services/Compositor.qml, plugin/src/Caelestia/Niri/).
#
# Usage: check-boundary.sh [--update-allowlist]
#   --update-allowlist  rewrite boundary-allowlist.txt with the current set of offending files
set -euo pipefail

root="${PORT_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
allowlist="$root/scripts/port/boundary-allowlist.txt"
cd "$root"

hypr_re='Quickshell\.Hyprland|\bHyprland\.|Hyprland[A-Z]|\bHypr\.|\bHypr(Extras|Devices)\b|hyprctl|GlobalShortcut'
niri_re='\bNiriIpc\b'

# Code only: docs, the port tooling itself and build outputs are out of scope.
scope=(
    --hidden
    -g '*.qml' -g '*.js' -g '*.cpp' -g '*.hpp' -g '*.h' -g 'CMakeLists.txt' -g '*.cmake'
    -g '*.nix' -g '*.sh' -g '*.fish' -g '*.kdl'
    -g '!.git' -g '!build/**' -g '!result*' -g '!*.md' -g '!docs/**' -g '!scripts/port/**'
)

hypr_files="$(rg -l "${scope[@]}" -e "$hypr_re" . | sed 's|^\./||' | sort -u || true)"
# Hyprland C++ sources are violations by name even without matching content.
hypr_srcs="$(find plugin -type f \( -name 'hypr*.cpp' -o -name 'hypr*.hpp' \) | sort -u || true)"
offenders="$(printf '%s\n%s\n' "$hypr_files" "$hypr_srcs" | sed '/^$/d' | sort -u)"

if [[ "${1:-}" == "--update-allowlist" ]]; then
    {
        echo "# Files still containing Hyprland code. Generated by check-boundary.sh --update-allowlist."
        echo "# Shrinking this list is the main progress metric of the niri port; it must reach 0 by S7."
        [[ -n "$offenders" ]] && echo "$offenders"
    } > "$allowlist"
    echo "allowlist updated: $(grep -cv '^#' "$allowlist" || true) files"
    exit 0
fi

allowed="$(grep -v '^#' "$allowlist" 2>/dev/null | sed '/^$/d' | sort -u || true)"
fail=0

new="$(comm -23 <(echo "$offenders" | sed '/^$/d') <(echo "$allowed" | sed '/^$/d'))"
if [[ -n "$new" ]]; then
    echo "ERROR: Hyprland code in files not in scripts/port/boundary-allowlist.txt:" >&2
    while read -r f; do
        rg -n "$hypr_re" "$f" | sed "s|^|  $f:|" >&2 || echo "  $f (hyprland source file)" >&2
    done <<< "$new"
    fail=1
fi

stale="$(comm -13 <(echo "$offenders" | sed '/^$/d') <(echo "$allowed" | sed '/^$/d'))"
if [[ -n "$stale" ]]; then
    echo "ERROR: files are clean but still allowlisted — remove them from boundary-allowlist.txt:" >&2
    echo "$stale" | sed 's/^/  /' >&2
    fail=1
fi

niri_bad="$(rg -n "${scope[@]}" -g '!services/Compositor.qml' -g '!plugin/src/Caelestia/Niri/**' \
    -g '!plugin/tests/niri/**' -e "$niri_re" . || true)"
if [[ -n "$niri_bad" ]]; then
    echo "ERROR: NiriIpc used outside services/Compositor.qml and plugin/src/Caelestia/Niri/:" >&2
    echo "$niri_bad" | sed 's/^/  /' >&2
    fail=1
fi

count="$(echo "$allowed" | sed '/^$/d' | wc -l)"
if ((fail)); then
    exit 1
fi
echo "boundary OK (allowlist: $count files)"

#!/usr/bin/env bash
# Fails on hardcoded FHS paths (/usr/, /bin/bash, /etc/) in QML, C++ and scripts — they do not
# exist (or differ) on NixOS. Allowed:
#   - fallbacks after an env lookup: `Quickshell.env("X") || "/usr/..."`
#   - `#!/usr/bin/env` shebangs (provided by NixOS)
#   - /etc/os-release (provided by NixOS)
#   - files listed in scripts/port/fhs-allowlist.txt (not yet fixed; must reach 0 by S8)
set -euo pipefail

root="${PORT_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
allowlist="$root/scripts/port/fhs-allowlist.txt"
cd "$root"

scope=(
    --hidden
    -g '*.qml' -g '*.js' -g '*.cpp' -g '*.hpp' -g '*.h' -g '*.sh' -g '*.fish' -g '*.bash'
    -g '!.git' -g '!build/**' -g '!result*' -g '!docs/**' -g '!scripts/port/**'
)

hits="$(rg -n "${scope[@]}" -e '/usr/|/bin/bash|/etc/' . | sed 's|^\./||' \
    | rg -v 'Quickshell\.env\([^)]*\)\s*\|\|' \
    | rg -v ':1:#!/usr/bin/env ' \
    | rg -v '/etc/os-release' || true)"

if [[ "${1:-}" == "--update-allowlist" ]]; then
    {
        echo "# Files with FHS paths not yet fixed. Generated by check-fhs.sh --update-allowlist."
        [[ -n "$hits" ]] && echo "$hits" | cut -d: -f1 | sort -u
    } > "$allowlist"
    echo "allowlist updated: $(grep -cv '^#' "$allowlist" || true) files"
    exit 0
fi

allowed="$(grep -v '^#' "$allowlist" 2>/dev/null | sed '/^$/d' | sort -u || true)"
bad="$(echo "$hits" | sed '/^$/d' | while IFS= read -r line; do
    f="${line%%:*}"
    grep -qxF "$f" <<< "$allowed" || echo "$line"
done)"

if [[ -n "$bad" ]]; then
    echo "ERROR: hardcoded FHS paths (use an env var set by the Nix wrapper instead):" >&2
    echo "$bad" | sed 's/^/  /' >&2
    exit 1
fi
echo "fhs OK (allowlist: $(echo "$allowed" | sed '/^$/d' | wc -l) files)"
